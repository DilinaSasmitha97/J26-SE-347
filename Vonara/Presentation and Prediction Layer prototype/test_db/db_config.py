"""
Connection settings for the synthetic test database.

Read from the component's `.env` (git-ignored). Two identities are used on
purpose, mirroring the production split:

  admin  - creates the database, tables and the reader account (seed.py only)
  reader - SELECT-only account used by member2_stub.py for every fixture query,
           so a fixture can never modify data even by mistake

Required in .env:
    MYSQL_ADMIN_PASSWORD
Optional (defaults shown):
    MYSQL_HOST=localhost  MYSQL_PORT=3306  MYSQL_ADMIN_USER=root
    MYSQL_DATABASE=c4_synthetic  MYSQL_READER_USER=c4_reader
    MYSQL_READER_PASSWORD   (generated by seed.py when absent)
"""

import os
import sys
from pathlib import Path

TEST_DB_DIR = Path(__file__).resolve().parent
COMPONENT_DIR = TEST_DB_DIR.parent
ENV_PATH = COMPONENT_DIR / ".env"
SCHEMA_PATH = TEST_DB_DIR / "schema.sql"
OUTPUT_DIR = TEST_DB_DIR / "output"

# The component's modules live one directory up; the test_db scripts import them.
if str(COMPONENT_DIR) not in sys.path:
    sys.path.insert(0, str(COMPONENT_DIR))

try:
    from dotenv import load_dotenv

    load_dotenv(ENV_PATH)
except ImportError:  # pragma: no cover - dotenv is in requirements.txt
    pass


class DatabaseNotConfigured(RuntimeError):
    """The .env file lacks the settings needed to reach MySQL."""


def setting(name: str, default: str = "") -> str:
    return os.getenv(name, default).strip()


def database_name() -> str:
    return setting("MYSQL_DATABASE", "c4_synthetic")


def _connect(user: str, password: str, database: str = None):
    import pymysql

    return pymysql.connect(
        host=setting("MYSQL_HOST", "localhost"),
        port=int(setting("MYSQL_PORT", "3306")),
        user=user,
        password=password,
        database=database,
        charset="utf8mb4",
        autocommit=False,
    )


def admin_connection(database: str = None):
    password = setting("MYSQL_ADMIN_PASSWORD")
    if not password:
        raise DatabaseNotConfigured(
            f"MYSQL_ADMIN_PASSWORD is not set in {ENV_PATH}. Add it there "
            "(the file is git-ignored) and re-run."
        )
    return _connect(setting("MYSQL_ADMIN_USER", "root"), password, database)


def reader_connection():
    password = setting("MYSQL_READER_PASSWORD")
    if not password:
        raise DatabaseNotConfigured(
            "MYSQL_READER_PASSWORD is not set. Run `python test_db/seed.py` "
            "first; it creates the read-only account and records the password."
        )
    return _connect(setting("MYSQL_READER_USER", "c4_reader"), password, database_name())


def schema_ddl() -> str:
    return SCHEMA_PATH.read_text(encoding="utf-8")
